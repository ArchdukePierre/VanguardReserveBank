local T = dofile(HERE .. "/lib.lua")
T.solo({}, function()
  local crypto = require("lib.crypto")
  local ser = require("lib.ser")
  local util = require("lib.util")
  T.eq(crypto.sha256(""), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", "sha empty")
  T.eq(crypto.sha256("abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", "sha abc")
  T.eq(crypto.sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"), "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1", "sha 56 bytes (two-block pad)")
  T.eq(crypto.sha256(string.rep("a", 1000)), "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3", "sha 1000")
  T.eq(crypto.hmac("Jefe", "what do ya want for nothing?"), "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843", "rfc4231 case 2")
  T.eq(crypto.hmac(string.rep("\170", 131), "Test Using Larger Than Block-Size Key - Hash Key First"), "60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54", "rfc4231 case 6 (long key)")
  T.eq(crypto.hmac(string.rep("ab", 32), "pin:ACC-123456:1234"), "27b2959fe2167affd66306d596aa8306e1c7dc41b442a2e9c77668f53acc1943", "v9 pin hash compatibility")
  T.check(crypto.self_test(), "self test")
  local msg = string.rep("transfer 12345 ", 40)
  local c = crypto.stream("key", "nonce1", msg)
  T.check(c ~= msg and #c == #msg, "cipher changes data, keeps length")
  T.eq(crypto.stream("key", "nonce1", c), msg, "stream roundtrip")
  T.check(crypto.stream("key", "nonce2", msg) ~= c, "nonce changes keystream")
  local a, b = crypto.random_hex(32), crypto.random_hex(32)
  T.check(#a == 32 and a:match("^%x+$") and a ~= b, "random hex")
  local c0 = crypto.compressions
  crypto.hmac("somekey", string.rep("x", 100))
  local first = crypto.compressions - c0
  c0 = crypto.compressions
  crypto.hmac("somekey", string.rep("x", 100))
  T.eq(crypto.compressions - c0, 3, "cached hmac of 100 bytes = 2 inner + 1 outer compressions (first call cost " .. first .. ")")

  local v = { a = 1, b = { 1, 2, 3, x = "q\"uo\nte\\" }, [5] = true, ["we ird"] = 1.5, n = -0.003, big = 123456789012 , ["end"] = 4 }
  local s = ser.encode(v)
  T.check(not s:find("\n"), "ser output is single line")
  local back = ser.decode(s)
  T.eq(back.b.x, "q\"uo\nte\\", "ser string escapes")
  T.eq(back["we ird"], 1.5, "ser odd key")
  T.eq(back.n, -0.003, "ser float")
  T.eq(back.big, 123456789012, "ser big int")
  T.eq(back["end"], 4, "ser reserved word key")
  T.eq(back[5], true, "ser sparse int key")
  T.eq(#back.b, 3, "ser array")
  T.check(ser.decode("os.exit()") == nil, "decode refuses code")
  T.eq(util.money(123456789), "$1,234,567.89", "money")
  T.eq(util.money(-5), "-$0.05", "money negative")
  T.eq(util.parse_money("12.5"), 1250, "parse money")
  T.eq(util.parse_money("$1,000"), 100000, "parse money commas")
  T.eq(util.parse_money("1.234"), nil, "parse money rejects sub-cent")
end)
T.done()
