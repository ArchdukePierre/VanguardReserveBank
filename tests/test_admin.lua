local function rpc(fn)
  local result
  N.run_client(world, seed, function()
    local Client = require("lib.client")
    local c = assert(Client.new({ admin = (require("lib.cfg")).read_key("admin.key") }))
    result = fn(function(m, p, admin) return c:call(m, p, { admin = admin ~= false }) end)
  end)
  return result
end

local function acct(id) return rpc(function(call) return call("admin_account_detail", { account_id = id }).account end) end

local function rig(w, h, id, files, terminal, wld)
  wld = wld or world
  local C
  if terminal then C = N.client_pc(wld, id, files or N.keys(), { w = w, h = h })
  else C = N.client_pc(wld, id, files or N.keys(), { monitors = { { w = w, h = h, scale = 0.5 } }, w = 51, h = 19 }) end
  local App = C.env.require("ui.app")
  local orig = App.new
  App.new = function(o)
    local a = orig(o)
    C.env.APP = a
    return a
  end
  local R = { C = C, mon = terminal and C.term or C.monitors[1], state = {} }
  local fn = function() require("roles.admin").run() end
  T.setenv(fn, C.env)
  wld:start(C, function()
    local ok, err = xpcall(fn, debug.traceback)
    R.state.done, R.state.ok, R.state.err = true, ok, err
  end)
  function R.settle(sec) wld:run({ seconds = sec or 1, max_steps = 5e7 }) end
  function R.value_color(label)
    local y = 0
    for line in (R.dump() .. "\n"):gmatch("(.-)\n") do
      y = y + 1
      if line:find(label, 1, true) then
        local x = #line:gsub("%s+$", "")
        return R.mon._T.fgs[y]:sub(x, x)
      end
    end
  end
  function R.dump() return R.mon._dump() end
  function R.show(tag)
    if DUMP then
      print("---- " .. tag .. " (" .. R.C.env.APP.s.w .. "x" .. R.C.env.APP.s.h .. ")")
      print(R.dump())
    end
  end
  function R.find(rid)
    local regs = C.env.APP.s.regions
    for i = #regs, 1, -1 do
      if regs[i].id == rid and not regs[i].disabled then return regs[i] end
    end
  end
  function R.tap(rid)
    local r = R.find(rid)
    if not r then
      T.check(false, "no region " .. tostring(rid) .. " on screen:\n" .. R.dump())
      return false
    end
    if terminal then C.queue[#C.queue + 1] = { "mouse_click", 1, r.x, r.y }
    else C.queue[#C.queue + 1] = { "monitor_touch", R.mon.__name, r.x, r.y } end
    R.settle(1)
    return true
  end
  function R.tap_text(text)
    local y = 0
    for line in (R.dump() .. "\n"):gmatch("(.-)\n") do
      y = y + 1
      local x = line:find(text, 1, true)
      if x then
        local regs = C.env.APP.s.regions
        for i = #regs, 1, -1 do
          local r = regs[i]
          if r.id ~= nil and x >= r.x and x < r.x + r.w and y >= r.y and y < r.y + r.h and not r.disabled then return R.tap(r.id) end
        end
      end
    end
    T.check(false, "nothing to tap with the text " .. text .. "\n" .. R.dump())
  end
  function R.reach(rid)
    for _ = 1, 12 do
      if R.find(rid) then return true end
      if not R.find("down") then break end
      R.tap("down")
    end
    return R.find(rid) ~= nil
  end
  function R.tap_prefix(prefix)
    local regs = C.env.APP.s.regions
    for i = 1, #regs do
      if type(regs[i].id) == "string" and regs[i].id:sub(1, #prefix) == prefix and not regs[i].disabled then return R.tap(regs[i].id) end
    end
    T.check(false, "no region starting with " .. prefix .. "\n" .. R.dump())
  end
  function R.chars(s)
    for ch in s:gmatch(".") do C.queue[#C.queue + 1] = { "char", ch }; R.settle(0.05) end
  end
  function R.key(code) C.queue[#C.queue + 1] = { "key", code, false }; R.settle(1) end
  function R.enter() R.key(257) end
  function R.type_text(s) R.chars(s); R.enter() end
  function R.digits(s)
    for ch in s:gmatch(".") do R.tap("key:" .. ch) end
  end
  function R.has(text, msg)
    local d = R.dump()
    return T.check(d:find(text, 1, true), (msg or "screen shows") .. ": " .. text .. "\n" .. d)
  end
  function R.hasnt(text, msg)
    local d = R.dump()
    return T.check(not d:find(text, 1, true), (msg or "screen does not show") .. ": " .. text .. "\n" .. d)
  end
  function R.layout(tag)
    local s = C.env.APP.s
    local regs = s.regions
    local bad
    for i, r in ipairs(regs) do
      if not (r.x >= 1 and r.y >= 1 and r.x + r.w - 1 <= s.w and r.y + r.h - 1 <= s.h) then bad = bad or ("region " .. tostring(r.id) .. " leaves the screen") end
      for j = i + 1, #regs do
        local q = regs[j]
        if r.x < q.x + q.w and q.x < r.x + r.w and r.y < q.y + q.h and q.y < r.y + r.h then
          bad = bad or ("regions " .. tostring(r.id) .. " and " .. tostring(q.id) .. " overlap")
        end
      end
    end
    T.check(not bad, tag .. " layout: " .. tostring(bad) .. "\n" .. R.dump())
  end
  function R.until_has(text, max)
    local waited = 0
    while waited < (max or 30) and not R.dump():find(text, 1, true) do R.settle(1); waited = waited + 1 end
    return R.has(text)
  end
  return R
end

