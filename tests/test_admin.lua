local function lint(path)
  local src = REPO_FILES[path]
  T.check(src, path .. " exists")
  if not src then return end
  T.check(not src:find("\226\128[\147\148]"), path .. " has no dashes outside plain ASCII")
  T.check(not src:find("[\240-\247]"), path .. " has no emoji")
  T.check(not src:find("goto ", 1, true), path .. " has no goto")
  for line in (src .. "\n"):gmatch("(.-)\n") do
    if line:find("format(", 1, true) and line:find("%d", 1, true) then T.check(false, path .. " uses %d in a format call: " .. line) end
  end
  local n = 0
  for line in (src .. "\n"):gmatch("(.-)\n") do
    n = n + 1
    if line:match("^%s*%-%-") then T.check(n == 1 and not line:match("^%s"), path .. " comment only on the first line") end
  end
  for _, word in ipairs({ "seamless", "robust", "powerful" }) do T.check(not src:lower():find(word, 1, true), path .. " avoids the word " .. word) end
end
lint("vrb/roles/admin.lua")
for path in pairs(REPO_FILES) do
  if path:match("^vrb/roles/admin/[%w_]+%.lua$") then lint(path) end
end

